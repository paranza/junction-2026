"""Rewrite translated questions into the English wording the native solvers read.

`question_templates.json` is generated by `ops/build_question_templates.py` from the
wording of the preview questions only; answers are never read. Labels, room numbers
and apartment letters are copied verbatim. Wording the table does not know is
returned unchanged.
"""
from __future__ import annotations

from functools import lru_cache
import json
from pathlib import Path
import re
import unicodedata

TABLE = Path(__file__).with_name("question_templates.json")


def _clean(text):
    return re.sub(r"\s+", " ", unicodedata.normalize("NFC", text)).strip()


@lru_cache(maxsize=1)
def _templates():
    data = json.loads(TABLE.read_text(encoding="utf-8"))
    translated = [(re.compile(row["pattern"]), row["english"]) for row in data["translated"]]
    english = [(re.compile(row["pattern"]), row["english"]) for row in data["english"]]
    return translated, english


def _fill(fmt, values):
    # A label with an apostrophe ('Cage d'escalier') would end a '...' quote early,
    # so such labels are written in curly double quotes, which the solvers also read.
    for key, value in values.items():
        if "'" in value:
            fmt = fmt.replace("'{%s}'" % key, "“{%s}”" % key)
    return fmt.format(**values)


def to_english(question: str) -> str:
    """English wording for a known translated template, else the question unchanged."""
    text = _clean(question)
    translated, english = _templates()
    for pattern, fmt in translated:
        match = pattern.match(text)
        if match:
            return _fill(fmt, match.groupdict())
    for pattern, fmt in english:
        match = pattern.match(text)
        if match and any("'" in v for v in match.groupdict().values()):
            return _fill(fmt, match.groupdict())
    return question
